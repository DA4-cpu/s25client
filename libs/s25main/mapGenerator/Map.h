namespace rttr::mapGenerator {

/// Basic kind of a node decided by CreateLandMasses
enum class NodeKind : uint8_t
{
    Water,
    Land,
    Mountain
};

class Map
{
private:
    std::vector<DescIdx<TerrainDesc>> terrains_;

public:
    NodeMapBase<uint8_t> z;
    /// Local humidity [0, 100] per node, independent of z (height). Generated by GenerateClimateMap()
    /// and used by Texturizer to pick between land textures of the same height band.
    NodeMapBase<uint8_t> climate;
    /// Local temperature [0, 100] per node, independent of z and climate. Generated by
    /// GenerateClimateMap() with a different seed and used together with climate by Texturizer.
    NodeMapBase<uint8_t> temperature;
    /// Water, land or mountain per node (see CreateLandMasses)
    NodeMapBase<NodeKind> nodeKind;
    /// Height of mountain nodes above the foot of the mountain (0 for other nodes), see CreateHeights
    NodeMapBase<uint8_t> mountainLift;
    /// Height in percent per node: 0 = sea level, 100 = highest point of the map (climate value "height")
    NodeMapBase<uint8_t> heightPercent;
    /// Index of the zone (WorldDescription::mapGen.zones) per node, see GenerateZones()
    NodeMapBase<uint8_t> zones;
    /// Terrain types per node as bit flags of MapGenTerrain, see ComputeTerrainFlags()
    NodeMapBase<uint16_t> terrainFlags;
    /// 1 for nodes on the course of a river, 0 otherwise
    NodeMapBase<uint8_t> riverCourse;
    /// 1 for water nodes of lakes (small bodies of water: fresh water, no beach), 0 otherwise. See MarkLakes()
    NodeMapBase<uint8_t> lakes;
    NodeMapBase<uint8_t> objectTypes;
    NodeMapBase<uint8_t> objectInfos;
    NodeMapBase<uint8_t> resources;
    NodeMapBase<libsiedler2::Animal> animals;
    std::vector<Triangle> harbors;
    std::vector<MapPoint> hqPositions;
    TextureMap textureMap;

    std::string name;
    const std::string author;
    const ValueRange<uint8_t> height;
    const uint8_t players;
    const MapExtent size;

    Map(const MapExtent& size, uint8_t players, const WorldDescription& worldDesc, DescIdx<LandscapeDesc> landscape,
        uint8_t maxHeight = 0x60);

    /**
     * Creates a new archiv for this map.
     *
     * @return a new archiv containing the information of this map
     */
    libsiedler2::Archiv CreateArchiv() const;

    NodeMapBase<TexturePair>& getTextures() { return textureMap.textures_; }
    const NodeMapBase<TexturePair>& getTextures() const { return textureMap.textures_; }
};

} // namespace rttr::mapGenerator
